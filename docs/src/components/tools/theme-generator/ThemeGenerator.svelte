		</p>

		<section class="tgSourceColorSection">
			<ColorField label="Primary" bind:value={inputs.primary} />
			<button type="button" class="tgSourceColorRandomizerButton" onclick={handleRandomAll}>
				{t('Random All')}
			</button>
		</section>

		{#each semanticFields.slice(1) as { key, label } (key)}
			<ColorField {label} bind:value={inputs[key]} />
		{/each}

		<h4>{t('Status Colors')}</h4>
		{#each statusFields as { key, label } (key)}
			<ColorField {label} bind:value={inputs[key]} />
		{/each}

		<button type="button" class="tgExportButton" onclick={handleExport}>
			{t('Export theme.css')}
		</button>
	</div>
	<div class="tgPreview">
		<DummyGraphPage colorMode="light" theme={palette.light} />
		<DummyGraphPage colorMode="dark" theme={palette.dark} />
	</div>
</div>

