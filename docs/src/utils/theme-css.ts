/**
 * Writes the `theme.css` the theme generator exports.
 *
 * Every variable name appears once, in the section table below, and that one
 * table writes the light `:root`, the `.dark` block and both halves of the
 * increased-contrast block, so a token cannot reach one of them and miss
 * another. `theme-css.spec.ts` holds the table to the shipped `defaults/theme.css`.
 */
import type { GeneratedTheme, ThemePalette } from './oklch';

interface PaletteToken {
	name: string;
	key: keyof ThemePalette;
	/** Declared in `:root` only. The shipped `.dark` block leaves it to inherit. */
	lightOnly?: boolean;
}

/** The same in every theme, so it is declared once in `:root` and never overridden. */
interface FixedToken {
	name: string;
	value: string;
}

interface Section {
	title: string;
	/** Explanation under the heading. `:root` carries it; the other blocks repeat the heading only. */
	note?: string[];
	tokens: Array<PaletteToken | FixedToken>;
}

