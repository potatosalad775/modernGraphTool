<script lang="ts">
	import {
		type PaletteInputs,
		type ThemePalette,
		generateFullPalette,
		oklchToHex,
		DEFAULT_INPUTS
	} from '../../../utils/oklch';
	import { createTranslator, type ToolLang } from '../../../i18n/tools';
	import ColorField from './ColorField.svelte';
	import DummyGraphPage from './DummyGraphPage.svelte';

	interface Props {
		lang: ToolLang;
	}

	let { lang }: Props = $props();
	// `$derived`, not a plain const: the const would capture only the initial
	// `lang`. Each route passes a fixed locale today, so this never actually
	// recomputes — but the reactive form is the one that stays correct.
	let t = $derived(createTranslator(lang));

	// ── CSS export template ────────────────────────────────────────────────────

	const generateThemeCssContent = (light: ThemePalette, dark: ThemePalette): string => {
		return `/*
 * modernGraphTool — Theme Variables
 * Generated by Theme Generator
 *
 * Graph variables control D3.js SVG rendering where Tailwind classes cannot be used.
 * Base variables follow DaisyUI naming — all UI chrome is derived via opacity modifiers.
 * All variables switch automatically between light and dark mode.
 */

:root {
\t/* ── Graph ─────────────────────────────────────────────────────────── */
\t--color-graph-bg: ${light.graphBg};
\t--color-graph-watermark-opacity: ${light.graphWatermarkOpacity};
\t--color-graph-grid-major: ${light.graphGridMajor};
\t--color-graph-grid-minor: ${light.graphGridMinor};
\t--color-graph-axis-label: ${light.graphAxisLabel};
\t--color-graph-grid-text: ${light.graphGridText};
\t--color-graph-baseline: ${light.graphBaseline};

\t/* ── Base ──────────────────────────────────────────────────────────── */
\t--color-base-100: ${light.base100};
\t--color-base-200: ${light.base200};
\t--color-base-300: ${light.base300};
\t--color-base-content: ${light.baseContent};
\t--color-primary: ${light.primary};
\t--color-primary-content: ${light.primaryContent};
\t--color-secondary: ${light.secondary};
\t--color-secondary-content: ${light.secondaryContent};
\t--color-accent: ${light.accent};
\t--color-accent-content: ${light.accentContent};
\t--color-neutral: ${light.neutral};
\t--color-neutral-content: ${light.neutralContent};
\t--color-info: ${light.info};
\t--color-info-content: ${light.infoContent};
\t--color-success: ${light.success};
\t--color-success-content: ${light.successContent};
\t--color-warning: ${light.warning};
\t--color-warning-content: ${light.warningContent};
\t--color-error: ${light.error};
\t--color-error-content: ${light.errorContent};
}

.dark {
\t/* ── Graph ─────────────────────────────────────────────────────────── */
\t--color-graph-grid-major: ${dark.graphGridMajor};
\t--color-graph-grid-minor: ${dark.graphGridMinor};
\t--color-graph-axis-label: ${dark.graphAxisLabel};
\t--color-graph-grid-text: ${dark.graphGridText};
\t--color-graph-baseline: ${dark.graphBaseline};

\t/* ── Base ──────────────────────────────────────────────────────────── */
\t--color-base-100: ${dark.base100};
\t--color-base-200: ${dark.base200};
\t--color-base-300: ${dark.base300};
\t--color-base-content: ${dark.baseContent};
\t--color-primary: ${dark.primary};
\t--color-primary-content: ${dark.primaryContent};
