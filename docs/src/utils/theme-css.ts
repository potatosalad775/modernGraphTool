const HEADER = `/*
 * modernGraphTool — Theme Variables
 * Generated by Theme Generator
 *
 * Graph variables control D3.js SVG rendering where Tailwind classes cannot be used.
 * Base variables follow DaisyUI naming — all UI chrome is derived via opacity modifiers.
 * All variables switch automatically between light and dark mode.
 */`;

const CONTRAST_HEADER = `/* ── Increased contrast ──────────────────────────────────────────────────────
 * Honours the OS "increase contrast" setting. Everything derived from
 * base-content (text steps, borders, dividers, scrollbars) follows it, so
 * pushing that one token to black / white lifts all of them at once. A fill
 * short of 7:1 (WCAG AAA) against its -content moves away from it until it
 * clears that, and a light-theme fill that darkens also clears 7:1 as text on
 * base-100. The light rating darkens to 7:1 on the base surfaces. Only the
 * tokens that change are listed; the rest keep their values above. */`;

/** The width of a section heading, matching the shipped file. */
const HEADING_WIDTH = 74;

function heading({ title, note }: Section, withNote: boolean): string[] {
	const lead = `/* ── ${title} `;
	if (!withNote || !note) return [`${lead}${'─'.repeat(HEADING_WIDTH - 3 - lead.length)} */`];
	const lines = note.map((line) => ` * ${line}`);
	lines[lines.length - 1] += ' */';
	return [lead + '─'.repeat(HEADING_WIDTH - 1 - lead.length), ...lines];
}

function declaration(name: string, value: string): string {
	return `--color-${name}: ${value};`;
}

/** A theme block: every token the mode declares, grouped under section headings. */
function themeBlock(palette: ThemePalette, mode: 'light' | 'dark'): string[] {
	const light = mode === 'light';
	const sections = THEME_ORDER.map((section) => ({
		section,
		lines: section.tokens.flatMap((token) => {
			if ('value' in token) return light ? [declaration(token.name, token.value)] : [];
			if (token.lightOnly && !light) return [];
			return [declaration(token.name, palette[token.key])];
		})
	})).filter(({ lines }) => lines.length > 0);
	return sections.flatMap(({ section, lines }, i) => [
		...(i > 0 ? [''] : []),
		...heading(section, light),
		...lines
	]);
}

/** A contrast block: only the tokens whose contrast value differs from the theme's. */
function contrastBlock(theme: ThemePalette, contrast: ThemePalette): string[] {
	return CONTRAST_ORDER.flatMap((section) =>
		section.tokens.flatMap((token) =>
			'key' in token && contrast[token.key] !== theme[token.key]
				? [declaration(token.name, contrast[token.key])]
				: []
		)
	);
}

function rule(selector: string, lines: string[], depth: number): string {
	const indent = (line: string, by: number) => (line ? '\t'.repeat(by) + line : '');
	return [
		indent(`${selector} {`, depth),
		...lines.map((line) => indent(line, depth + 1)),
		indent('}', depth)
	].join('\n');
}

export function renderThemeCss(theme: GeneratedTheme): string {
	const media = [
		rule(':root', contrastBlock(theme.light, theme.contrast.light), 1),
		rule('.dark', contrastBlock(theme.dark, theme.contrast.dark), 1)
	].join('\n\n');
	return [
		HEADER,
		rule(':root', themeBlock(theme.light, 'light'), 0),
		rule('.dark', themeBlock(theme.dark, 'dark'), 0),
		`${CONTRAST_HEADER}\n@media (prefers-contrast: more) {\n${media}\n}\n`
	].join('\n\n');
}
