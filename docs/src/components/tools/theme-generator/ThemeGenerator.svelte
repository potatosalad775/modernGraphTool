\t--color-secondary-content: ${dark.secondaryContent};
\t--color-accent: ${dark.accent};
\t--color-accent-content: ${dark.accentContent};
\t--color-neutral: ${dark.neutral};
\t--color-neutral-content: ${dark.neutralContent};
\t--color-info: ${dark.info};
\t--color-info-content: ${dark.infoContent};
\t--color-success: ${dark.success};
\t--color-success-content: ${dark.successContent};
\t--color-warning: ${dark.warning};
\t--color-warning-content: ${dark.warningContent};
\t--color-error: ${dark.error};
\t--color-error-content: ${dark.errorContent};
}
`;
	};

	// ── Random color generation helpers ────────────────────────────────────────

	function randomHex(): string {
		return (
			'#' +
			Math.floor(Math.random() * 16777215)
				.toString(16)
				.padStart(6, '0')
		);
	}

	function randomSemanticHex(
		hueCenter: number,
		hueSpread: number,
		lRange: [number, number],
		cRange: [number, number]
	): string {
		const h = hueCenter + (Math.random() - 0.5) * hueSpread;
		const l = lRange[0] + Math.random() * (lRange[1] - lRange[0]);
		const c = cRange[0] + Math.random() * (cRange[1] - cRange[0]);
		return oklchToHex({ l, c, h: ((h % 360) + 360) % 360 });
	}

	// ── State ──────────────────────────────────────────────────────────────────

	let inputs = $state<PaletteInputs>({ ...DEFAULT_INPUTS });

	/*
	 * The React original debounced this behind a 50ms `setTimeout` because every
	 * `SketchPicker` drag fired a state update that re-rendered both previews.
	 * `generateFullPalette` is pure arithmetic over ~20 colours, and Svelte
	 * updates only the inline styles that actually changed, so the debounce —
	 * and the visible lag it introduced on every edit — is not needed.
	 */
	let palette = $derived(generateFullPalette(inputs));

	const semanticFields = [
		{ key: 'primary', label: 'Primary' },
		{ key: 'secondary', label: 'Secondary' },
		{ key: 'accent', label: 'Accent' }
	] as const;

	const statusFields = [
		{ key: 'info', label: 'Info' },
		{ key: 'success', label: 'Success' },
		{ key: 'warning', label: 'Warning' },
		{ key: 'error', label: 'Error' }
	] as const;

	function handleRandomAll() {
		inputs = {
			baseHue: Math.floor(Math.random() * 360),
			primary: randomHex(),
			secondary: randomHex(),
			accent: randomSemanticHex(280, 60, [0.4, 0.55], [0.01, 0.06]),
			info: randomSemanticHex(220, 40, [0.6, 0.75], [0.12, 0.2]),
			success: randomSemanticHex(130, 40, [0.65, 0.8], [0.15, 0.25]),
			warning: randomSemanticHex(75, 30, [0.7, 0.85], [0.14, 0.22]),
			error: randomSemanticHex(15, 20, [0.55, 0.7], [0.18, 0.26])
		};
	}

	function handleBaseHueChange(raw: number) {
		if (Number.isNaN(raw)) return;
		inputs.baseHue = Math.max(0, Math.min(360, raw));
	}

	function handleExport() {
		const css = generateThemeCssContent(palette.light, palette.dark);
		const blob = new Blob([css], { type: 'text/css' });
		const url = URL.createObjectURL(blob);
		const a = document.createElement('a');
		a.href = url;
		a.download = 'theme.css';
		document.body.appendChild(a);
		a.click();
		document.body.removeChild(a);
		URL.revokeObjectURL(url);
	}
</script>

